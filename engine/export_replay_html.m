function export_replay_html(match_result, output_filepath)
% EXPORT_REPLAY_HTML Generates a standalone interactive HTML replay viewer.

    json_data = jsonencode(match_result);

    html = [
    "<!DOCTYPE html><html lang='en'><head><meta charset='UTF-8'>"
    "<title>CUAS Villach - Battleship Replay</title>"
    "<style>"
    "  body { background: #0b132b; color: #e0fbfc; font-family: 'Segoe UI', Tahoma, sans-serif; text-align: center; margin: 0; padding: 20px; }"
    "  h1 { margin: 5px 0; color: #5bc0be; letter-spacing: 1px; }"
    "  .subtitle { color: #8d99ae; margin-bottom: 15px; font-size: 14px; }"
    "  .arena { display: flex; justify-content: center; gap: 40px; flex-wrap: wrap; margin-top: 15px; }"
    "  .player-card { background: #1c2541; padding: 20px; border-radius: 12px; box-shadow: 0 8px 20px rgba(0,0,0,0.5); border: 1px solid #3a506b; }"
    "  .player-title { font-size: 20px; font-weight: bold; margin-bottom: 8px; color: #6fffe9; }"
    "  .hp-bar-bg { background: #0b132b; height: 14px; border-radius: 7px; overflow: hidden; margin-bottom: 15px; border: 1px solid #3a506b; }"
    "  .hp-bar-fill { background: linear-gradient(90deg, #06d6a0, #118ab2); height: 100%; width: 100%; transition: width 0.2s; }"
    "  .grid { display: grid; grid-template-columns: repeat(10, 34px); grid-template-rows: repeat(10, 34px); gap: 3px; background: #0b132b; padding: 6px; border-radius: 6px; }"
    "  .cell { width: 34px; height: 34px; background: #162447; border-radius: 3px; display: flex; align-items: center; justify-content: center; font-weight: bold; font-size: 14px; transition: all 0.15s; }"
    "  .ship { background: #3a506b; border: 1px solid #5bc0be; }"
    "  .miss { background: #1f4068; color: #8d99ae; }"
    "  .hit { background: #e63946 !important; color: #fff; box-shadow: 0 0 8px #e63946; }"
    "  .sunk { background: #6a040f !important; color: #ffb703; border: 1px solid #ffb703; }"
    "  .last-shot { outline: 3px solid #ffb703; z-index: 2; transform: scale(1.08); }"
    "  .controls { margin: 20px auto; background: #1c2541; padding: 15px 25px; border-radius: 10px; display: inline-flex; align-items: center; gap: 12px; border: 1px solid #3a506b; }"
    "  button, select { background: #3a506b; color: white; border: none; padding: 8px 16px; border-radius: 6px; cursor: pointer; font-weight: bold; font-size: 14px; }"
    "  button:hover { background: #5bc0be; color: #0b132b; }"
    "  input[type=range] { width: 220px; accent-color: #5bc0be; }"
    "  #status-log { font-size: 18px; font-weight: bold; color: #ffb703; min-height: 28px; margin-top: 10px; }"
    "</style></head><body>"
    "<h1>CUAS VILLACH - BATTLESHIP AI ARENA</h1>"
    "<div class='subtitle'>Interactive Pre-Calculated Match Replay</div>"
    "<div id='status-log'>Press Play to start the replay!</div>"
    "<div class='controls'>"
    "  <button onclick='step(-1)'>&#9664; Prev</button>"
    "  <button id='play-btn' onclick='togglePlay()'>&#9654; Play</button>"
    "  <button onclick='step(1)'>Next &#9654;</button>"
    "  <input type='range' id='slider' min='0' value='0' oninput='jumpTo(this.value)'>"
    "  <span id='turn-label'>Shot: 0 / 0</span>"
    "  <select id='speed-select' onchange='updateSpeed()'>"
    "    <option value='400'>1x Speed</option>"
    "    <option value='150' selected>2.5x Speed</option>"
    "    <option value='50'>MAX Speed</option>"
    "  </select>"
    "</div>"
    "<div class='arena'>"
    "  <div class='player-card'>"
    "    <div class='player-title' id='p1-name'>Bot 1</div>"
    "    <div class='hp-bar-bg'><div class='hp-bar-fill' id='hp1-bar'></div></div>"
    "    <div class='grid' id='grid2'></div>"
    "    <div style='margin-top:8px; font-size:12px; color:#8d99ae;'>Target Grid (Bot 1 shooting at Bot 2)</div>"
    "  </div>"
    "  <div class='player-card'>"
    "    <div class='player-title' id='p2-name'>Bot 2</div>"
    "    <div class='hp-bar-bg'><div class='hp-bar-fill' id='hp2-bar'></div></div>"
    "    <div class='grid' id='grid1'></div>"
    "    <div style='margin-top:8px; font-size:12px; color:#8d99ae;'>Target Grid (Bot 2 shooting at Bot 1)</div>"
    "  </div>"
    "</div>"
    "<script>"
    "const data = " + string(json_data) + ";"
    "let currentIdx = 0; let timer = null; let speed = 150;"
    "const hist = Array.isArray(data.history) ? data.history : [data.history];"
    "document.getElementById('p1-name').innerText = data.bot1_name;"
    "document.getElementById('p2-name').innerText = data.bot2_name;"
    "document.getElementById('slider').max = hist.length;"
    "function initGrids() {"
    "  for (let p=1; p<=2; p++) {"
    "    const g = document.getElementById('grid'+p); g.innerHTML = '';"
    "    const board = p===1 ? data.board1 : data.board2;"
    "    for (let r=0; r<10; r++) {"
    "      for (let c=0; c<10; c++) {"
    "        const div = document.createElement('div');"
    "        div.id = `g${p}_${r}_${c}`;"
    "        div.className = 'cell' + (board[r][c] > 0 ? ' ship' : '');"
    "        g.appendChild(div);"
    "      }"
    "    }"
    "  }"
    "}"
    "function renderState(idx) {"
    "  initGrids();"
    "  let hp1 = 17, hp2 = 17;"
    "  for (let i=0; i<idx; i++) {"
    "    const h = hist[i];"
    "    const targetGrid = h.player === 1 ? 2 : 1;"
    "    const cell = document.getElementById(`g${targetGrid}_${h.row-1}_${h.col-1}`);"
    "    if (h.outcome === 'MISS') { cell.classList.add('miss'); cell.innerHTML = '&bull;'; }"
    "    else if (h.outcome === 'HIT' || h.outcome === 'SUNK') { cell.classList.add('hit'); cell.innerHTML = '&#10005;'; }"
    "    if (h.outcome === 'SUNK') {"
    "      const b = targetGrid === 1 ? data.board1 : data.board2;"
    "      for (let r=0; r<10; r++) for (let c=0; c<10; c++)"
    "        if (b[r][c] === h.sunk_id) document.getElementById(`g${targetGrid}_${r}_${c}`).classList.add('sunk');"
    "    }"
    "    if (i === idx-1) cell.classList.add('last-shot');"
    "    hp1 = h.hp1; hp2 = h.hp2;"
    "  }"
    "  document.getElementById('hp1-bar').style.width = (hp1/17*100) + '%';"
    "  document.getElementById('hp2-bar').style.width = (hp2/17*100) + '%';"
    "  document.getElementById('turn-label').innerText = `Shot: ${idx} / ${hist.length}`;"
    "  document.getElementById('slider').value = idx;"
    "  if (idx === 0) { document.getElementById('status-log').innerText = 'Ready to start!'; }"
    "  else if (idx === hist.length) {"
    "    const wName = data.winner === 1 ? data.bot1_name : data.bot2_name;"
    "    document.getElementById('status-log').innerHTML = `&#127942; WINNER: ${wName} in ${data.turns} turns!`;"
    "  } else {"
    "    const h = hist[idx-1];"
    "    const shooter = h.player === 1 ? data.bot1_name : data.bot2_name;"
    "    document.getElementById('status-log').innerText = `Turn ${h.turn}: ${shooter} fires at (${h.row},${h.col}) -> ${h.outcome}!`;"
    "  }"
    "}"
    "function step(dir) { currentIdx = Math.max(0, Math.min(hist.length, currentIdx + dir)); renderState(currentIdx); }"
    "function jumpTo(val) { currentIdx = parseInt(val); renderState(currentIdx); }"
    "function updateSpeed() { speed = parseInt(document.getElementById('speed-select').value); if (timer) { stopPlay(); startPlay(); } }"
    "function togglePlay() { if (timer) stopPlay(); else startPlay(); }"
    "function startPlay() {"
    "  if (currentIdx >= hist.length) currentIdx = 0;"
    "  document.getElementById('play-btn').innerHTML = '&#9208; Pause';"
    "  timer = setInterval(() => { if (currentIdx < hist.length) step(1); else stopPlay(); }, speed);"
    "}"
    "function stopPlay() { clearInterval(timer); timer = null; document.getElementById('play-btn').innerHTML = '&#9654; Play'; }"
    "renderState(0);"
    "</script></body></html>"
    ];

    fid = fopen(output_filepath, 'w', 'n', 'UTF-8');
    fprintf(fid, '%s\n', html);
    fclose(fid);
    fprintf('Replay saved to: %s\n', output_filepath);
end
